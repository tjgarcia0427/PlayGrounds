"""Original rigid-weighted plush feasibility rig; Blender 4.0 background only.
Usage: blender -b -t 2 -P tools/unimate/create_seed.py -- /tmp/plush-seed.glb
This seed animation is hand-authored, NOT generated by UniMate.
"""
import bpy
import math
import sys
from pathlib import Path

out = Path(sys.argv[sys.argv.index('--') + 1]).resolve()
out.parent.mkdir(parents=True, exist_ok=True)
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)
scene = bpy.context.scene
scene.render.fps = 30
scene.frame_start, scene.frame_end = 1, 120
# Blender Z-up, facing -Y. glTF exporter converts to Y-up.
bones = [
    ('Root', None, (0,0,0), (0,0,.25)),
    ('Hips','Root',(0,0,.6),(0,0,.9)),
    ('Spine','Hips',(0,0,.9),(0,0,1.25)),
    ('Head','Spine',(0,0,1.25),(0,0,1.8)),
    ('L_UpperArm','Spine',(.32,0,1.23),(.65,0,1.23)),
    ('L_Forearm','L_UpperArm',(.65,0,1.23),(.87,0,1.23)),
    ('L_Hand','L_Forearm',(.87,0,1.23),(1.02,0,1.23)),
    ('R_UpperArm','Spine',(-.32,0,1.23),(-.65,0,1.23)),
    ('R_Forearm','R_UpperArm',(-.65,0,1.23),(-.87,0,1.23)),
    ('R_Hand','R_Forearm',(-.87,0,1.23),(-1.02,0,1.23)),
    ('L_Thigh','Hips',(.19,0,.65),(.19,0,.34)),
    ('L_Shin','L_Thigh',(.19,0,.34),(.19,0,.14)),
    ('L_Foot','L_Shin',(.19,0,.14),(.19,-.2,.1)),
    ('R_Thigh','Hips',(-.19,0,.65),(-.19,0,.34)),
    ('R_Shin','R_Thigh',(-.19,0,.34),(-.19,0,.14)),
    ('R_Foot','R_Shin',(-.19,0,.14),(-.19,-.2,.1)),
]
arm = bpy.data.armatures.new('PlushSkeleton')
rig = bpy.data.objects.new('PlushRig', arm)
scene.collection.objects.link(rig)
bpy.context.view_layer.objects.active = rig
rig.select_set(True)
bpy.ops.object.mode_set(mode='EDIT')
for name, parent, head, tail in bones:
    bone = arm.edit_bones.new(name)
    bone.head, bone.tail = head, tail
    if parent:
        bone.parent = arm.edit_bones[parent]
bpy.ops.object.mode_set(mode='OBJECT')

def material(name, color):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get('Principled BSDF')
    bsdf.inputs['Base Color'].default_value = (*color, 1)
    bsdf.inputs['Roughness'].default_value = .9
    return mat
cream = material('Oat plush', (.78,.65,.48))
face = material('Vanilla face', (.96,.86,.68))
lilac = material('Lilac headphones', (.59,.48,.75))
ink = material('Soft charcoal', (.035,.027,.046))

def part(name, bone, center, scale, mat):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=24, ring_count=16, location=center)
    obj = bpy.context.object
    obj.name, obj.scale = name, scale
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    obj.data.materials.append(mat)
    for p in obj.data.polygons:
        p.use_smooth = True
    group = obj.vertex_groups.new(name=bone)
    group.add(list(range(len(obj.data.vertices))), 1, 'REPLACE')
    mod = obj.modifiers.new('PlushSkin', 'ARMATURE')
    mod.object = rig
    obj.parent = rig

part('Body','Spine',(0,0,.94),(.42,.31,.5),cream)
part('Head','Head',(0,0,1.56),(.47,.35,.46),cream)
part('Face','Head',(0,-.305,1.54),(.34,.07,.29),face)
for side, x in [('L',1),('R',-1)]:
    part(side+' upper arm',side+'_UpperArm',(x*.49,0,1.23),(.24,.15,.16),cream)
    part(side+' forearm',side+'_Forearm',(x*.76,0,1.23),(.18,.14,.14),cream)
    part(side+' mitten',side+'_Hand',(x*.95,0,1.23),(.13,.14,.14),cream)
    part(side+' thigh',side+'_Thigh',(x*.19,0,.48),(.18,.19,.24),cream)
    part(side+' shin',side+'_Shin',(x*.19,0,.24),(.16,.17,.16),cream)
    part(side+' foot',side+'_Foot',(x*.19,-.08,.13),(.19,.25,.13),cream)
    part(side+' earcup','Head',(x*.46,0,1.56),(.10,.24,.25),lilac)
    part(side+' eye','Head',(x*.12,-.373,1.58),(.033,.025,.045),ink)
part('Smile','Head',(0,-.381,1.44),(.053,.013,.016),ink)
# Upper half of a torus forms a headphone band, weighted to Head.
for i in range(9):
    a = i * math.pi / 8
    part('Band %02d'%i,'Head',(.46*math.cos(a),0,1.6+.43*math.sin(a)),(.07,.09,.07),lilac)

# One mesh is essential: upstream export uses the selected mesh skin weights.
bpy.ops.object.select_all(action="DESELECT")
meshes = [o for o in scene.objects if o.type == "MESH"]
for obj in meshes:
    obj.select_set(True)
bpy.context.view_layer.objects.active = meshes[0]
bpy.ops.object.join()
bpy.context.object.name = "PlushSkin"

# A seamless four-second gentle seed sway, all bones keyed for preprocessing.
# First/last frames match. Ground/feet stay fixed; this is not a locomotion clip.
for frame in range(1, 121):
    phase = (frame-1)/119 * math.tau
    for bone in rig.pose.bones:
        bone.rotation_mode = 'XYZ'
        bone.rotation_euler = (0,0,0)
        if bone.name == 'Head':
            bone.rotation_euler[1] = .2 * math.sin(phase)
        elif bone.name in ('L_UpperArm', 'R_UpperArm', 'L_Forearm', 'R_Forearm'):
            bone.rotation_euler[0] = .6 * math.sin(phase)
        bone.keyframe_insert(data_path='rotation_euler', frame=frame)
rig.animation_data.action.name = 'seed_sway_HAND_AUTHORED'
for curve in rig.animation_data.action.fcurves:
    for key in curve.keyframe_points:
        key.interpolation = 'LINEAR'
scene.frame_set(1)
bpy.ops.export_scene.gltf(filepath=str(out), export_format='GLB', export_animations=True,
    export_skins=True, export_force_sampling=True, export_frame_range=True)
print('EXPORTED seed rig:', out, 'bones:', len(bones))

# Optional local CPU preview, excluded from the exported asset.
if '--preview' in sys.argv:
    from mathutils import Vector
    preview = Path(sys.argv[sys.argv.index('--preview')+1]).resolve()
    scene.frame_set(30)
    bpy.ops.mesh.primitive_plane_add(size=200)
    bpy.context.object.data.materials.append(material('Backdrop',(.84,.8,.88)))
    bpy.ops.object.camera_add(location=(2.8,-5.4,2.6))
    camera = bpy.context.object
    camera.rotation_euler = (Vector((0,0,1.05))-camera.location).to_track_quat('-Z','Y').to_euler()
    camera.data.type = 'ORTHO'
    camera.data.ortho_scale = 3.2
    scene.camera = camera
    bpy.ops.object.light_add(type='AREA', location=(1,-3,5))
    bpy.context.object.data.energy = 450
    bpy.context.object.data.shape = 'DISK'
    bpy.context.object.data.size = 4
    scene.world.use_nodes = True
    scene.world.node_tree.nodes['Background'].inputs[0].default_value = (.8,.8,.8,1)
    scene.world.node_tree.nodes['Background'].inputs[1].default_value = .6
    scene.render.engine = 'CYCLES'
    scene.cycles.device = 'CPU'
    scene.cycles.samples = 16
    scene.cycles.use_denoising = False
    scene.render.resolution_x = scene.render.resolution_y = 600
    scene.render.resolution_percentage = 100
    scene.render.filepath = str(preview)
    bpy.ops.render.render(write_still=True)
